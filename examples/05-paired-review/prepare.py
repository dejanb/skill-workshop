"""Build identical read-only review workspaces, with one skill-access difference."""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path


HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
TARGET = REPO / "fixtures" / "part3-review"
SKILL = REPO / "plugins" / "dev" / "skills" / "security-review" / "SKILL.md"
MARKER = ".generated-by-part3-review-example"


def prepare(reset: bool = False) -> Path:
    if TARGET.exists():
        if not reset:
            raise FileExistsError(f"{TARGET} exists; rerun with --reset to rebuild it")
        if not (TARGET / MARKER).is_file():
            raise ValueError(
                f"Refusing to remove {TARGET}: generated marker is missing"
            )
        shutil.rmtree(TARGET)

    TARGET.mkdir(parents=True)
    (TARGET / MARKER).write_text("Generated by examples/05-paired-review/prepare.py\n")
    for condition in ("baseline", "with-skill"):
        changes = TARGET / condition / "changes"
        shutil.copytree(HERE / "cases", changes)

    skill_dir = TARGET / "with-skill" / ".claude" / "skills" / "security-review"
    skill_dir.mkdir(parents=True)
    shutil.copy2(SKILL, skill_dir / "SKILL.md")
    return TARGET


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--reset", action="store_true", help="Rebuild a previously generated fixture"
    )
    args = parser.parse_args()
    print(f"Prepared paired workspaces at {prepare(args.reset)}")


if __name__ == "__main__":
    main()
